def parse_city(venue_text: str) -> str:
    """
    從場館名稱、城市文字或地址推斷城市。
    找不到時回傳空字串。
    """
    if not venue_text:
        return ""

    lower = venue_text.lower()
    for keyword, city in _VENUE_CITY_MAP.items():
        if keyword.lower() in lower:
            return city

    return ""
